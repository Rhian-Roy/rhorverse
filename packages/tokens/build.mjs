#!/usr/bin/env node
// Generates the Tailwind v4 @theme block in apps/web/src/app/globals.css and
// src/tokens.ts from tokens.json. `--check` fails if outputs are stale.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(resolve(here, "tokens.json"), "utf8"));
const cssPath = resolve(here, "../../apps/web/src/app/globals.css");
const tsPath = resolve(here, "src/tokens.ts");
const START = "/* @tokens:start — generated by packages/tokens/build.mjs, do not edit */";
const END = "/* @tokens:end */";
const check = process.argv.includes("--check");

const { semantic, ...ramps } = tokens.color;
const resolveRef = (v) =>
  v.replace(/^\{(\w+)\.(\w+)\}$/, (_, ramp, step) => {
    const hit = ramps[ramp]?.[step];
    if (!hit) throw new Error(`Unknown token reference ${v}`);
    return hit;
  });

const lines = ["--color-*: initial;", "--font-*: initial;", ""];
for (const [ramp, steps] of Object.entries(ramps))
  for (const [step, hex] of Object.entries(steps)) lines.push(`--color-${ramp}-${step}: ${hex};`);
lines.push("");
for (const [name, ref] of Object.entries(semantic)) lines.push(`--color-${name}: ${resolveRef(ref)};`);
lines.push("");
for (const [name, v] of Object.entries(tokens.font)) lines.push(`--font-${name}: ${v};`);
lines.push("");
for (const [name, v] of Object.entries(tokens.text)) lines.push(`--text-${name}: ${v};`);
lines.push("", `--spacing: ${tokens.spacing};`, "");
for (const [name, v] of Object.entries(tokens.radius)) lines.push(`--radius-${name}: ${v};`);
lines.push("");
for (const [name, v] of Object.entries(tokens.motion.ease)) lines.push(`--ease-${name}: ${v};`);
for (const [name, v] of Object.entries(tokens.motion.duration)) lines.push(`--duration-${name}: ${v};`);

const block = [START, "@theme {", ...lines.map((l) => (l ? `  ${l}` : "")), "}", END].join("\n");

let css;
try {
  css = readFileSync(cssPath, "utf8");
} catch {
  css = `@import "tailwindcss";\n\n${START}\n${END}\n`;
}
const s = css.indexOf(START);
const e = css.indexOf(END);
if (s === -1 || e === -1) throw new Error(`Token markers missing in ${cssPath}`);
const nextCss = css.slice(0, s) + block + css.slice(e + END.length);

const ms = (v) => Number.parseInt(v, 10);
const nextTs = `// Generated by packages/tokens/build.mjs — do not edit.
export const color = ${JSON.stringify(
  Object.fromEntries(Object.entries(semantic).map(([k, v]) => [k, resolveRef(v)])),
  null,
  2,
)} as const;

export const duration = ${JSON.stringify(
  Object.fromEntries(Object.entries(tokens.motion.duration).map(([k, v]) => [k, ms(v)])),
  null,
  2,
)} as const;

export const ease = ${JSON.stringify(
  Object.fromEntries(
    Object.entries(tokens.motion.ease).map(([k, v]) => [
      k,
      v.slice(v.indexOf("(") + 1, -1).split(",").map(Number),
    ]),
  ),
  null,
  2,
)} as const;
`;

if (check) {
  const stale = [];
  if (nextCss !== css) stale.push(cssPath);
  try {
    if (readFileSync(tsPath, "utf8") !== nextTs) stale.push(tsPath);
  } catch {
    stale.push(tsPath);
  }
  if (stale.length) {
    console.error(`Tokens out of date, run \`pnpm --filter @rhorverse/tokens build\`:\n${stale.join("\n")}`);
    process.exit(1);
  }
  console.log("tokens up to date");
} else {
  writeFileSync(cssPath, nextCss);
  mkdirSync(dirname(tsPath), { recursive: true });
  writeFileSync(tsPath, nextTs);
  console.log(`tokens → ${cssPath}\ntokens → ${tsPath}`);
}
